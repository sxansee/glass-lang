#pragma once

namespace glass {

// Интерактивная консоль поверх существующего пайплайна (Lexer -> Parser ->
// Sema -> BodyChecker -> Compiler -> VM). Читает фрагменты Glass-кода из
// stdin, отдельно копит декларации верхнего уровня (mold/facet/fn, кроме
// main) и операторы тела синтетического main, и на каждом шаге заново
// компилирует и исполняет накопленную программу целиком — движок не умеет
// добавлять код в уже запущенную VM, поэтому это самый честный вариант
// "REPL" при нынешней архитектуре. Печатается только новый вывод print() —
// то, что не показывалось на предыдущих шагах, — так что накопление не
// выглядит как повторяющийся спам в консоли.
//
// Запускается из main(), когда glassc вызван без аргументов (см. main.cpp).
// Возвращает код возврата процесса.
int runRepl();

} // namespace glass
